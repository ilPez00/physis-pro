#!/usr/bin/env python3
"""E84 — can structured rules reach the contradictions the dictionary cannot?

E83 measured a WordNet antonym + negation rule at precision 1.000 and recall
0.143 on pairs not built from a dictionary, and named the five classes it
missed: number, comparison, modality, quantifier scope and argument order. The
obvious conclusion was "this is where a parser earns its cost". Before paying
for one, this asks how far targeted surface rules get — still no model, still no
tagger.

Rules, each aimed at one class and each able to fire wrongly:

  antonym      a WordNet antonym spans the pair                      (E83)
  negation     one side negates what the other asserts               (E83)
  numeric      the same measurement frame with different numbers
  comparative  opposed comparison words around a shared quantity
  modal        the same modal with opposed polarity
  quantifier   universal against negative-universal or existential
  roles        the same two nouns around the same verb, order swapped

Fixture: `fixtures/contradiction-holdout.json`, 36 hand-written pairs across
seven classes plus eleven paraphrases that must not fire. None is generated by
inserting a dictionary antonym, so no rule here can grade its own generator.

    python3 benchmarks/conatus/e84_structured_rules.py
"""
import argparse, json, os, re, sys
from collections import Counter, defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wordnet import WordNet  # noqa: E402
from e83_contradiction import (NEGATORS, antonym_rule, content_words,  # noqa: E402
                               negation_rule)

FIXTURE = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "fixtures", "contradiction-holdout.json")

NUMBER = re.compile(r"\b(\d+(?:\.\d+)?)\b")
WORD_NUMBER = {"one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6,
               "seven": 7, "eight": 8, "nine": 9, "ten": 10, "a pair": 2}
COMPARATIVES = [("above", "below"), ("over", "under"), ("more", "less"),
                ("higher", "lower"), ("faster", "slower"), ("rose", "fell"),
                ("increased", "decreased"), ("longer", "shorter"), ("up", "down")]
MODALS = ("must", "should", "may", "can", "will", "shall")
NEGATIVE_MODAL = re.compile(r"\b(must|should|may|can|will|shall)\s+(not|never)\b")
UNIVERSAL = ("every", "all", "each")
NEGATIVE_UNIVERSAL = ("no", "none", "nothing", "never")
EXISTENTIAL = ("some", "several", "a few")
PERMIT = {"permitted": "forbidden", "allowed": "forbidden", "mandatory": "optional",
          "required": "forbidden", "forbidden": "permitted", "optional": "mandatory"}
# Oppositions this repository already declares. `relation.rs` types Supports and
# Contradicts, Precedes and Follows, as distinct relations; their surface verbs
# are opposites in this domain, and WordNet does not link them (it missed
# `supported`/`contradicted` in the held-out set).
DOMAIN_OPPOSITES = {
    "supported": "contradicted", "supports": "contradicts", "confirms": "refutes",
    "confirmed": "refuted", "validated": "invalidated", "precedes": "follows",
    "passed": "failed", "succeeded": "failed", "beats": "loses",
}
DOMAIN_OPPOSITES.update({v: k for k, v in list(DOMAIN_OPPOSITES.items())})


def numbers_in(text):
    found = [float(m) for m in NUMBER.findall(text)]
    lowered = text.lower()
    for word, value in WORD_NUMBER.items():
        if re.search(rf"\b{word}\b", lowered):
            found.append(float(value))
    return found


def frame_of(text):
    """The sentence with every quantity removed — two sentences sharing a frame
    are about the same measurement.

    Word numbers have to be blanked too: `Two stalls` against `Five stalls` left
    the words in the frame, the frames differed, and the rule refused a
    contradiction it was written to catch."""
    lowered = re.sub(NUMBER, "#", text.lower())
    for word in sorted(WORD_NUMBER, key=len, reverse=True):
        lowered = re.sub(rf"\b{word}\b", "#", lowered)
    return " ".join(w for w in lowered.split() if w not in ("a", "the", "an"))


def numeric_rule(item):
    a, b = numbers_in(item["a"]), numbers_in(item["b"])
    if not a or not b or sorted(a) == sorted(b):
        return False
    # Same frame, different quantity. Without the frame check, any two
    # sentences with different numbers would contradict.
    return frame_of(item["a"]) == frame_of(item["b"])


def comparative_rule(item):
    a, b = item["a"].lower(), item["b"].lower()
    for left, right in COMPARATIVES:
        if (re.search(rf"\b{left}\b", a) and re.search(rf"\b{right}\b", b)) or \
           (re.search(rf"\b{right}\b", a) and re.search(rf"\b{left}\b", b)):
            return len(content_words(a) & content_words(b)) >= 2
    return False


def modal_rule(item):
    a, b = item["a"].lower(), item["b"].lower()
    for modal in MODALS:
        in_a, in_b = re.search(rf"\b{modal}\b", a), re.search(rf"\b{modal}\b", b)
        if in_a and in_b:
            neg_a = bool(NEGATIVE_MODAL.search(a))
            neg_b = bool(NEGATIVE_MODAL.search(b))
            if neg_a != neg_b and len(content_words(a) & content_words(b)) >= 2:
                return True
    # Deontic opposites carried by a single word rather than by polarity.
    for word, opposite in PERMIT.items():
        if re.search(rf"\b{word}\b", a) and re.search(rf"\b{opposite}\b", b):
            return len(content_words(a) & content_words(b)) >= 1
    return False


def _stems(text):
    """Content words with a trailing plural `s` removed, because `sessions`
    and `session` are the same word for the purpose of asking whether two
    sentences are about the same thing — that mismatch alone sank the
    `none/every` pair."""
    return {w[:-1] if len(w) > 3 and w.endswith("s") else w for w in content_words(text)}


def quantifier_rule(item):
    a, b = item["a"].lower(), item["b"].lower()
    def has(words, text):
        return any(re.search(rf"\b{w}\b", text) for w in words)
    shared = len(_stems(a) & _stems(b)) >= 1
    if not shared:
        return False
    del shared  # kept above for readability; the guard already returned
    return ((has(UNIVERSAL, a) and has(NEGATIVE_UNIVERSAL, b)) or
            (has(NEGATIVE_UNIVERSAL, a) and has(UNIVERSAL, b)) or
            (has(UNIVERSAL, a) and has(EXISTENTIAL, b) and
             (has(("failed", "not"), b) or has(("passed",), a))) or
            (has(EXISTENTIAL, a) and has(UNIVERSAL, b) and
             (has(("failed", "not"), a) or has(("passed",), b))))


def roles_rule(item):
    """The same two nouns around the same verb, in opposite order. Crude, and
    deliberately so: it is the cheapest thing that can see argument order."""
    a = [w for w in re.findall(r"[a-z]+", item["a"].lower()) if w not in ("the", "a", "an")]
    b = [w for w in re.findall(r"[a-z]+", item["b"].lower()) if w not in ("the", "a", "an")]
    if len(a) < 3 or len(b) < 3 or Counter(a) != Counter(b):
        return False       # not the same words -> not a role swap
    return a != b          # same multiset, different order


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fixture", default=FIXTURE)
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    data = json.load(open(args.fixture))
    items = data["pairs"]
    wn = WordNet()
    cache = {}

    def domain_rule(item):
        a, b = item["a"].lower(), item["b"].lower()
        for word, opposite in DOMAIN_OPPOSITES.items():
            if re.search(rf"\b{word}\b", a) and re.search(rf"\b{opposite}\b", b):
                return len(_stems(a) & _stems(b)) >= 1
        return False

    rules = {
        "antonym": lambda i: antonym_rule(wn, i, cache),
        "domain": domain_rule,
        "negation": negation_rule,
        "numeric": numeric_rule,
        "comparative": comparative_rule,
        "modal": modal_rule,
        "quantifier": quantifier_rule,
        "roles": roles_rule,
    }

    fired = {name: [rule(i) for i in items] for name, rule in rules.items()}
    any_fired = [any(fired[name][k] for name in rules) for k in range(len(items))]
    labels = [i["contradiction"] for i in items]
    classes = [i["class"] for i in items]

    print(f"fixture: {len(items)} pairs · "
          f"{sum(labels)} contradictions, {len(items) - sum(labels)} paraphrases")

    print(f"\n{'rule':13}{'fires':>7}{'correct':>9}{'false+':>8}")
    for name in rules:
        f = sum(fired[name])
        correct = sum(1 for k in range(len(items)) if fired[name][k] and labels[k])
        print(f"{name:13}{f:7}{correct:9}{f - correct:8}")

    tp = sum(1 for k in range(len(items)) if any_fired[k] and labels[k])
    fp = sum(1 for k in range(len(items)) if any_fired[k] and not labels[k])
    fn = sum(1 for k in range(len(items)) if not any_fired[k] and labels[k])
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    print(f"\nall rules together: precision {precision:.3f} recall {recall:.3f} "
          f"({tp} caught, {fp} false positive(s), {fn} missed)")
    print(f"E83's dictionary-only arm on its held-out set: precision 1.000 recall 0.143")

    print(f"\n{'class':13}{'caught':>8}{'of':>4}")
    by_class = defaultdict(lambda: [0, 0])
    for k, item in enumerate(items):
        if not labels[k]:
            continue
        slot = by_class[classes[k]]
        slot[0] += any_fired[k]
        slot[1] += 1
    for name, (caught, total) in sorted(by_class.items()):
        print(f"{name:13}{caught:8}{total:4}")

    missed = [items[k] for k in range(len(items)) if labels[k] and not any_fired[k]]
    if missed:
        print("\nstill missed:")
        for item in missed:
            print(f"   [{item['class']}] {item['a'][:52]} || {item['b'][:52]}")
    wrong = [items[k] for k in range(len(items)) if not labels[k] and any_fired[k]]
    if wrong:
        print("\nfalse positives (paraphrases the rules called contradictions):")
        for item in wrong:
            print(f"   {item['a'][:52]} || {item['b'][:52]}")

    if args.out:
        json.dump({"precision": precision, "recall": recall,
                   "by_class": {k: v for k, v in by_class.items()},
                   "fired": {k: sum(v) for k, v in fired.items()}},
                  open(args.out, "w"), indent=1)


if __name__ == "__main__":
    main()
